def build_solutions(papers: list[dict], problems: list[dict]) -> list[dict]:
    prob_of_tag: dict[str, set[str]] = defaultdict(set)
    for p in papers:
        for t in p["problemTags"]:
            for s in p["solutionTags"]:
                prob_of_tag[s].add(t)

    by_tag: dict[str, list[dict]] = defaultdict(list)
    for p in papers:
        for t in p["solutionTags"]:
            by_tag[t].append(p)

    prob_labels = {pr["id"]: pr["shortLabel"] for pr in problems}
    solutions = []
    for tag, plist in by_tag.items():
        plist = sorted(plist, key=lambda p: (p["year"], p["id"]))
        probs = sorted(prob_of_tag[tag], key=lambda t: -sum(
            1 for p in plist if t in p["problemTags"]))
        summary = plist[0]["contributions"][0]
        if len(summary) > 220:
            summary = summary[:217].rstrip() + "…"
        solutions.append({
            "id": tag,
            "name": title_case(tag),
            "category": canon_category(tag),
            "summary": summary,
            "firstYear": plist[0]["year"],
            "paperCount": len(plist),
            "paperIds": [p["id"] for p in plist],
            "addresses": probs[:6],
            **({"simulator": SIM_LINKS[tag]} if tag in SIM_LINKS else {}),
        })
    solutions.sort(key=lambda x: (-x["paperCount"], x["firstYear"], x["id"]))
    return solutions


