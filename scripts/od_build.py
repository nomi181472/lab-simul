def build_papers(manifest: list[dict], harvest: dict[str, dict]) -> list[dict]:
    papers = []
    for m in manifest:
        h = harvest[m["id"]]
        prob = h["problem"]["problemTags"]
        sol = h["solution"]["solutionTags"]
        prob = [PROBLEM_ALIASES.get(t, t) for t in prob]
        sol = [SOLUTION_ALIASES.get(t, t) for t in sol]
        prob = list(dict.fromkeys(prob))
        sol = list(dict.fromkeys(sol))
        papers.append({
            "id": m["id"],
            "arxiv": m.get("arxiv"),
            "title": m["title"],
            "shortTitle": short_title(m["title"]),
            "year": m["year"],
            "authors": m.get("authors", [])[:8],
            "fileName": m["fileName"],
            "files": m["files"],
            "venue": h.get("venue") or m.get("venue"),
            "doi": h["citations"].get("doi") or m.get("doi"),
            "pdfUrl": m.get("pdfUrl"),
            "citations": m.get("citations"),
            "pages": m.get("pages"),
            "tags": (prob + sol)[:8],
            "problemTags": prob,
            "solutionTags": sol,
            "summary": h["solution"]["summary"],
            "problemSummary": h["problem"]["summary"],
            "contributions": [h["solution"]["approach"]]
            + h["solution"]["components"][:6],
            "limitations": h["limitations"]["items"][:5],
            "datasets": list(dict.fromkeys(
                canon_dataset(d) for d in h["technical"]["datasets"])),
            "metrics": list(dict.fromkeys(
                canon_metric(x) for x in h["technical"]["metrics"])),
            "benchmarks": [
                {**{k: v for k, v in b.items() if v},
                 "dataset": canon_dataset(b["dataset"]),
                 "metric": canon_metric(b["metric"])}
                for b in h["experiments"]["benchmarks"]
            ],
            "futureDirections": h["futureDirections"],
            "industryApplications": h["industry"]["applications"],
            "deploymentClaims": h["industry"]["deploymentClaims"][:6],
            "evidences": list(dict.fromkeys(prob + sol)),
            "harvestFile": f"papers/object_detection/harvest/{m['id']}.json",
        })
    return papers


