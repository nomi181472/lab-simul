def canon_metric(raw: str) -> str:
    s = re.sub(r"\s+", " ", raw).strip()
    low = s.lower()
    if low in METRIC_EXACT:
        return METRIC_EXACT[low]
    # direct dict first
    direct = {
        "ap": "AP", "map": "mAP", "ap50": "AP50", "ap75": "AP75",
        "fps": "FPS", "flops": "FLOPs", "gflops": "GFLOPs",
        "latency (ms)": "latency (ms)", "latency": "latency",
        "parameters": "parameters", "recall": "recall", "precision": "precision",
        "map@[.5:.95]": "mAP", "map@[0.5:0.95]": "mAP", "map@[.5,.95]": "mAP",
        "mAP@0.5": "AP50", "mAP50": "AP50", "mAP75": "AP75",
        "params": "parameters", "fps ": "FPS", "f1": "F1",
        "ar": "AR", "ar100": "AR", "ar@100": "AR", "ar1k": "AR", "ar@1k": "AR",
        "aps": "APs", "apm": "APm", "apl": "APL",
        "ap_s": "APs", "ap_m": "APm", "ap_l": "APL",
        "top-1": "top-1 accuracy", "top-5": "top-5 accuracy",
        "gflops": "GFLOPs", "gflops": "GFLOPs", "gFLOPs": "GFLOPs",
    }
    if low in direct:
        return direct[low]
    for pat, rep in METRIC_RULES:
        if rep is None:
            continue
        m = re.match(pat, low)
        if m:
            return rep(m) if callable(rep) else rep
    return s


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:48]


def short_title(title: str) -> str:
    if ":" in title:
        head = title.split(":")[0].strip()
        if 2 <= len(head) <= 34:
            return head
    words = title.split()
    return " ".join(words[:4]) if len(" ".join(words[:5])) <= 40 else " ".join(words[:3])


def ts(obj) -> str:
    return json.dumps(obj, indent=1, ensure_ascii=False)


def num(raw: str) -> float | None:
    m = re.search(r"-?\d+(?:\.\d+)?", raw.replace(",", ""))
    return float(m.group(0)) if m else None


# ------------------------------------------------------------------- load data

def load() -> tuple[list[dict], dict[str, dict], dict]:
    manifest = json.loads(MANIFEST.read_text())
    harvest: dict[str, dict] = {}
    for p in sorted(HARVEST.glob("OD*.json")):
        rec = json.loads(p.read_text())
        harvest[rec["id"]] = rec
    judgments = json.loads(JUDGMENTS.read_text()) if JUDGMENTS.exists() else {}
    missing = [m["id"] for m in manifest if m["id"] not in harvest]
    if missing:
        raise SystemExit(f"missing harvest records: {missing}")
    return manifest, harvest, judgments


