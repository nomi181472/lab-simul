def build_benchmarks(papers: list[dict]) -> tuple[list[dict], list[dict]]:
    obs = []
    for p in papers:
        for b in p["benchmarks"]:
            v = num(str(b.get("value", "")))
            if v is None:
                continue
            obs.append({
                "paperId": p["id"],
                "year": p["year"],
                "dataset": b["dataset"],
                "metric": b["metric"],
                "value": v,
                "raw": str(b["value"]),
                **({"split": b["split"]} if b.get("split") else {}),
                **({"location": b["location"]} if b.get("location") else {}),
            })
    best: dict[tuple, dict] = {}
    for o in sorted(obs, key=lambda x: x["year"]):
        key = (o["dataset"], o["metric"])
        cur = best.get(key)
        if cur is None or o["value"] > cur["value"]:
            best[key] = o
    best_rows = [
        {"dataset": k[0], "metric": k[1], "year": v["year"],
         "paperId": v["paperId"], "value": v["value"]}
        for k, v in sorted(best.items(), key=lambda kv: (kv[0][0], kv[0][1]))
    ]
    return obs, best_rows


