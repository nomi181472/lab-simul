def title_case(slug: str) -> str:
    keep = {"iou", "nms", "fps", "coco", "voc", "clip", "nas", "cnn", "fdr", "dfl"}
    parts = []
    for w in slug.split("-"):
        parts.append(w.upper() if w in keep else w.capitalize())
    return " ".join(parts)


def short_label(slug: str) -> str:
    return " ".join(w.capitalize() for w in slug.split("-"))


