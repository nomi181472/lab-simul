def main() -> int:
    global harvest_global
    manifest, harvest, judgments = load()
    harvest_global = harvest
    OUT.mkdir(parents=True, exist_ok=True)

    papers = build_papers(manifest, harvest)
    problems = build_problems(papers, harvest, judgments)
    solutions = build_solutions(papers, problems)
    datasets, metrics = build_datasets_metrics(papers)
    obs, best = build_benchmarks(papers)
    rels = build_relations(papers, harvest)
    states = build_years(papers, problems, judgments)
    deltas = build_year_deltas(states, papers)

