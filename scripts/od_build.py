def norm_key(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "", s.lower())


def build_relations(papers: list[dict], harvest: dict) -> list[dict]:
    index: dict[str, str] = {}
    for p in papers:
        index[norm_key(p["title"])] = p["id"]
        index[norm_key(p["shortTitle"])] = p["id"]
        if p["arxiv"]:
            index[p["arxiv"]] = p["id"]
    # alias keys with punctuation removed for relatedWork names
    rels = []
    for p in papers:
        h = harvest[p["id"]]
        for rw in h["background"].get("relatedWork", []):
            name = norm_key(rw.get("name", ""))
            if not name or len(name) < 4:
                continue
            target = index.get(name)
            if target is None:
                # containment match against titles (skip self)
                for k, tid in index.items():
                    if tid != p["id"] and (name in k or k in name) and len(k) >= 6:
                        target = tid
                        break
            if target and target != p["id"]:
                rels.append({
                    "from": p["id"],
                    "to": target,
                    "kind": "buildsOn",
                    "relation": rw.get("relation", "prior work"),
                    **({"quote": rw["quote"]} if rw.get("quote") else {}),
                })
    # dedupe
    seen = set()
    out = []
    for r in rels:
        key = (r["from"], r["to"], r["relation"][:40])
        if key in seen:
            continue
        seen.add(key)
        out.append(r)
    return out


