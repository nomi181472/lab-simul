def build_year_deltas(states: list[dict], papers: list[dict]) -> list[dict]:
    deltas = []
    for a, b in zip(states, states[1:]):
        sa, sb = set(a["dominantApproaches"] + a["emergingIdeas"]), \
            set(b["dominantApproaches"])
        added = sorted(sb - sa)
        removed = sorted(sa - sb)
        persisted = sorted(sa & sb)
        new_probs = b["newProblems"]
        summary = (
            f"{b['year']}: {b['paperCount']} papers. "
            + (f"+{len(added)} approaches ({', '.join(added[:4])}). " if added else "")
            + (f"−{len(removed)} approaches. " if removed else "")
            + (f"New problems: {', '.join(new_probs[:3])}." if new_probs
               else "No new problem tags.")
        )
        deltas.append({
            "from": a["year"],
            "to": b["year"],
            "added": added,
            "removed": removed,
            "persisted": persisted,
            "newProblems": new_probs,
            "summary": summary,
            "supportingPapers": sorted(
                set(a["supportingPapers"]) | set(b["supportingPapers"])),
        })
    return deltas


