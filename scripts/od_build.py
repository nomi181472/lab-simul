def build_datasets_metrics(papers: list[dict]) -> tuple[list[dict], list[dict]]:
    ds: dict[str, dict] = {}
    for p in papers:
        for d in p["datasets"]:
            e = ds.setdefault(d, {"name": d, "years": [], "paperIds": []})
            if p["year"] not in e["years"]:
                e["years"].append(p["year"])
            e["paperIds"].append(p["id"])
    datasets = []
    for d, e in sorted(ds.items(), key=lambda kv: -len(kv[1]["paperIds"])):
        years = sorted(e["years"])
        datasets.append({
            "id": slug(d),
            "name": d,
            "years": years,
            "paperIds": sorted(set(e["paperIds"])),
            "note": (f"Used by {len(set(e['paperIds']))} papers, "
                     f"{years[0]}–{years[-1]}"),
        })

    mt: dict[str, set] = defaultdict(set)
    for p in papers:
        for m in p["metrics"]:
            mt[m].add(p["id"])
    metrics = []
    for m, ids in sorted(mt.items(), key=lambda kv: -len(kv[1])):
        metrics.append({
            "id": slug(m),
            "name": m,
            "paperCount": len(ids),
            "papers": sorted(ids),
            "note": f"Reported by {len(ids)} papers",
        })
    return datasets, metrics


