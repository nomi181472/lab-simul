def emit_bundles(papers: list[dict], problems: list[dict], harvest: dict) -> None:
    BUNDLE.mkdir(parents=True, exist_ok=True)

    # 1. cluster candidates
    clusters = []
    for pr in problems:
        if pr["paperCount"] < 3:
            continue
        sol_counter: Counter = Counter()
        for p in papers:
            if pr["id"] in p["problemTags"]:
                for s in p["solutionTags"]:
                    sol_counter[s] += 1
        ids = sorted({pid for o in pr["occurrences"] for pid in o["papers"]})
        clusters.append({
            "problemId": pr["id"],
            "shortLabel": pr["shortLabel"],
            "problem": pr["problem"][:300],
            "paperCount": pr["paperCount"],
            "firstYear": pr["firstObservedYear"],
            "lastYear": pr["lastObservedYear"],
            "papers": ids,
            "topSolutionTags": [t for t, _ in sol_counter.most_common(8)],
            "sampleStatements": pr["statements"][:4],
            "sampleEvidence": [e for o in pr["occurrences"]
                               for e in o["evidence"]][:6],
        })
    (BUNDLE / "cluster_candidates.json").write_text(ts(clusters))

    # 2. future directions + later-paper index
    dirs = []
    for p in papers:
        for i, f in enumerate(p["futureDirections"]):
            dirs.append({
                "uid": f"{p['id']}-f{i}",
                "paperId": p["id"],
                "year": p["year"],
                "direction": f["direction"],
                "quote": f["quote"],
                "location": f.get("location"),
            })
    later = [
        {"id": p["id"], "year": p["year"], "title": p["title"],
         "solutionTags": p["solutionTags"], "problemTags": p["problemTags"],
         "summary": p["summary"][:220]}
        for p in papers
    ]
    (BUNDLE / "future_directions.json").write_text(
        ts({"directions": dirs, "papers": later}))

    # 3. industry bundle
    apps, claims = [], []
    for p in papers:
        for a in p["industryApplications"]:
            apps.append({"paperId": p["id"], "year": p["year"], **a})
        for c in p["deploymentClaims"]:
            claims.append({"paperId": p["id"], "year": p["year"], "claim": c})
    (BUNDLE / "industry_bundle.json").write_text(ts({"applications": apps,
                                                     "deploymentClaims": claims}))

    # 4. saturation bundle
    sat = []
    for pr in problems:
        per_year = {o["year"]: len(o["papers"]) for o in pr["occurrences"]}
        span = pr["lastObservedYear"] - pr["firstObservedYear"] + 1
        sat.append({
            "problemId": pr["id"],
            "shortLabel": pr["shortLabel"],
            "firstYear": pr["firstObservedYear"],
            "lastYear": pr["lastObservedYear"],
            "paperCount": pr["paperCount"],
            "attemptCount": sum(len(o["attemptedSolutions"])
                                for o in pr["occurrences"]),
            "papersPerYear": round(pr["paperCount"] / span, 2),
            "papersPerActiveYear": round(
                pr["paperCount"] / max(1, len(per_year)), 2),
            "perYear": per_year,
            "currentStatus": pr["currentStatus"],
            "statements": pr["statements"][:3],
            "recentPapers": [pid for o in pr["occurrences"][-3:]
                             for pid in o["papers"]],
        })
    (BUNDLE / "saturation_bundle.json").write_text(ts(sat))


