def emit_harvest_records(harvest: dict[str, dict]) -> str:
    """Emit every remaining harvest field (verbatim, uncapped) as a
    lazy-loadable TS module keyed by paper id."""
    out: dict[str, dict] = {}
    for pid, h in sorted(harvest.items()):
        quoted = lambda ev: [  # noqa: E731
            {k: v for k, v in e.items() if k in ("quote", "location") and v}
            for e in ev
        ]
        out[pid] = {
            "problem": {
                "summary": h["problem"]["summary"],
                "statements": h["problem"]["statements"],
                "evidence": quoted(h["problem"]["evidence"]),
            },
            "background": {
                "summary": h["background"]["summary"],
                "relatedWork": [
                    {k: v for k, v in r.items()
                     if k in ("name", "relation", "quote", "location") and v}
                    for r in h["background"]["relatedWork"]
                ],
                "evidence": quoted(h["background"]["evidence"]),
            },
            "solution": {
                "summary": h["solution"]["summary"],
                "approach": h["solution"]["approach"],
                "components": h["solution"]["components"],
                "evidence": quoted(h["solution"]["evidence"]),
            },
            "experiments": {
                "summary": h["experiments"]["summary"],
                "baselines": h["experiments"]["baselines"],
                "evidence": quoted(h["experiments"]["evidence"]),
            },
            "limitations": {
                "summary": h["limitations"]["summary"],
                "items": h["limitations"]["items"],
                "evidence": quoted(h["limitations"]["evidence"]),
            },
            "industry": {"evidence": quoted(h["industry"]["evidence"])},
            "technical": {
                "algorithms": h["technical"]["algorithms"],
                "backbones": h["technical"]["backbones"],
                "models": h["technical"]["models"],
                "equations": [
                    {k: v for k, v in eq.items()
                     if k in ("name", "expr", "location") and v}
                    for eq in h["technical"]["equations"]
                ],
            },
        }
    body = json.dumps(out, separators=(",", ":"), ensure_ascii=False)
    (OUT / "harvest-records.ts").write_text(
        GENERATED_NOTE
        + 'import type { PaperHarvest } from "./types";\n\n'
        + "/* Full harvest records, verbatim and uncapped. Imported lazily by\n"
        + " * the paper explorer so the 1.5MB payload stays out of the main chunk. */\n"
        + f"export const HARVEST_RECORDS: Record<string, PaperHarvest> = {body};\n"
    )
    n_quotes = sum(
        len(s["evidence"]) for r in out.values()
        for s in (r["problem"], r["background"], r["solution"],
                  r["experiments"], r["limitations"], r["industry"])
    )
    return (f"harvest-records.ts {len(out)} records, {n_quotes} section quotes, "
            f"{len(body) // 1024}KB")


