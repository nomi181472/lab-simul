def build_problems(papers: list[dict], harvest: dict, judgments: dict) -> list[dict]:
    by_tag: dict[str, list[dict]] = defaultdict(list)
    for p in papers:
        for t in p["problemTags"]:
            by_tag[t].append(p)

    status_j = judgments.get("problemStatuses", {})
    problems = []
    for tag, plist in by_tag.items():
        plist = sorted(plist, key=lambda p: (p["year"], p["id"]))
        # statements: earliest-first, deduped, capped
        stmts: list[str] = []
        seen: set[str] = set()
        for p in plist + plist[::-1]:
            h = harvest[p["id"]]
            for s in h["problem"]["statements"]:
                key = re.sub(r"\s+", " ", s.lower())[:80]
                if key in seen:
                    continue
                seen.add(key)
                stmts.append(s)
            if len(stmts) >= 14:
                break
        # occurrences by year
        by_year: dict[int, list[dict]] = defaultdict(list)
        for p in plist:
            by_year[p["year"]].append(p)
        occurrences = []
        for year in sorted(by_year):
            group = by_year[year]
            attempted = []
            evidence = []
            for p in group:
                h = harvest[p["id"]]
                quote = next(
                    (e["quote"] for e in h["solution"]["evidence"][:3]), None)
                attempted.append({
                    "paperId": p["id"],
                    "shortTitle": p["shortTitle"],
                    "year": year,
                    "approach": h["solution"]["approach"],
                    "solutionTags": p["solutionTags"],
                    **({"quote": quote} if quote else {}),
                })
                pq = next(
                    (e["quote"] for e in h["problem"]["evidence"][:3]), None)
                if pq:
                    evidence.append({"paperId": p["id"], "quote": pq})
            occurrences.append({
                "year": year,
                "papers": [p["id"] for p in group],
                "attemptedSolutions": attempted[:8],
                "evidence": evidence[:6],
            })
        j = status_j.get(tag, {})
        problems.append({
            "id": tag,
            "shortLabel": short_label(tag),
            "problem": stmts[0] if stmts else short_label(tag),
            "statements": stmts[:14],
            "firstObservedYear": plist[0]["year"],
            "lastObservedYear": plist[-1]["year"],
            "paperCount": len(plist),
            "occurrences": occurrences,
            "currentStatus": j.get("status", "uncertain"),
            "statusEvidence": j.get("statusEvidence", ""),
            "statusPapers": j.get("statusPapers", []),
        })
    problems.sort(key=lambda x: (-x["paperCount"], x["firstObservedYear"], x["id"]))
    return problems


