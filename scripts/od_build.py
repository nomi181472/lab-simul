    emit_problems(problems)
    emit_solutions(solutions)
    emit_datasets_metrics(datasets, metrics)
    emit_benchmarks(obs, best)
    emit_relations(rels)
    emit_years(states)
    emit_year_deltas(deltas)
    emit_audit()
    emit_bundles(papers, problems, harvest)
    print(emit_harvest_records(harvest))
    for line in render_analysis():
        print(f"{line}")

    print(f"papers.ts          {len(papers)} papers")
    print(f"problems.ts        {len(problems)} problems "
          f"({sum(1 for p in problems if p['currentStatus'] != 'uncertain')} judged)")
    print(f"solutions.ts       {len(solutions)} solutions")
    print(f"datasets.ts        {len(datasets)} datasets")
    print(f"metrics.ts         {len(metrics)} metrics")
    print(f"benchmarks.ts      {len(obs)} observations, {len(best)} best-per-key")
    print(f"relations.ts       {len(rels)} paper->paper links")
