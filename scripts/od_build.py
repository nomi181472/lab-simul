def build_years(papers: list[dict], problems: list[dict],
                judgments: dict) -> list[dict]:
    years = sorted({p["year"] for p in papers})
    status_j = judgments.get("problemStatuses", {})
    prob_first = {pr["id"]: pr["firstObservedYear"] for pr in problems}
    prob_last = {pr["id"]: pr["lastObservedYear"] for pr in problems}
    prob_status = {pr["id"]: pr["currentStatus"] for pr in problems}
    rare_problems = {pr["id"] for pr in problems if pr["paperCount"] <= 4}

    sol_counts_year: dict[int, Counter] = defaultdict(Counter)
    prob_counts_year: dict[int, Counter] = defaultdict(Counter)
    for p in papers:
        for t in p["solutionTags"]:
            sol_counts_year[p["year"]][t] += 1
        for t in p["problemTags"]:
            prob_counts_year[p["year"]][t] += 1

    sol_names = {}
    # filled by caller via solutions list is easier; recompute label inline
    states = []
    for i, y in enumerate(years):
        yp = [p for p in papers if p["year"] == y]
        sc = sol_counts_year[y]
        pc = prob_counts_year[y]
        prev = sol_counts_year[years[i - 1]] if i else Counter()
        dom = [t for t, _ in sc.most_common(6)]
        emerging = [t for t in sc if t not in prev]
        declining = [t for t in prev
                     if prev[t] >= 3 and sc.get(t, 0) <= prev[t] // 2]
        new_probs = [t for t in pc if prob_first.get(t) == y]
        persist = [t for t in pc
                   if sum(1 for yy in years[:i] if prob_counts_year[yy].get(t)) >= 2]
        solved = [t for t in pc
                  if prob_status.get(t) in ("resolved", "reduced")
                  and prob_last.get(t) == y]
        unsolved = [t for t in pc
                    if prob_status.get(t) in ("persistent", "transformed",
                                              "uncertain")]
        math_dev = []
        arch_dev = []
        comp_dev = []
        apps = []
        dirs = []
        for p in yp:
            h = harvest_global[p["id"]]
            for eq in h["technical"]["equations"][:3]:
                s = eq.get("name") or eq.get("expr", "")
                if s and s not in math_dev:
                    math_dev.append(s)
            for t in p["solutionTags"]:
                if canon_category(t) == "architecture" and t not in arch_dev:
                    if t in emerging or sc[t] >= 3:
                        arch_dev.append(t)
            for b in p["benchmarks"]:
                if b["metric"] == "FPS" and len(comp_dev) < 6:
                    comp_dev.append(f"{p['shortTitle']}: {b['value']} FPS")
            for a in p["industryApplications"]:
                if a["domain"] not in apps:
                    apps.append(a["domain"])
            for f in p["futureDirections"][:3]:
                d = f["direction"]
                if len(d) > 140:
                    d = d[:137] + "…"
                if d not in dirs:
                    dirs.append(d)
        edge = sorted(t for t in pc if t in rare_problems)
        states.append({
            "year": y,
            "paperCount": len(yp),
            "dominantApproaches": dom,
            "emergingIdeas": emerging,
            "decliningIdeas": declining,
            "persistentProblems": persist,
            "newProblems": new_probs,
            "solvedOrReducedProblems": solved,
            "unsolvedProblems": unsolved,
            "mathematicalDevelopments": math_dev[:6],
            "architecturalDevelopments": arch_dev[:8],
            "computationalDevelopments": comp_dev[:6],
            "applications": apps[:8],
            "edgeCases": edge[:6],
            "researchDirections": dirs[:8],
            "supportingPapers": [p["id"] for p in yp],
        })
    return states


