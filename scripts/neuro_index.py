#!/usr/bin/env python3
"""Index the Neuroevolution corpus and emit the typed manifest.

For every downloaded PDF this extracts text once (cached), counts pages, and
classifies the paper along axes the lab actually needs:

  phenotype  what the search produced (MLP, CNN, neurocontroller, program, ...)
  family     which evolutionary algorithm (GA, GP, ES, QD, novelty search, ...)
  encoding   how a genome maps to that phenotype (direct, indirect, ...)
  loci       *which part of the candidate the operators change*
  layers     the evolved network's layer list, when the paper enumerates it
  relevance  neuroevolution / adjacent / off-topic, from the paper's own text

The layer list is the lab's centrepiece — a neuroevolution paper is hard to
read without it — so it is extracted with explicit, quoted evidence rather than
guessed. When a paper does not enumerate its network, `layers` stays empty and
the UI says so.

Unlike scripts/wifi_index.py this writes no architecture into the manifest: the
layer list and operator set are record-level, not corpus-level, and live in
data/papers/*.ts (generated by scripts/neuro_records.py).
"""

