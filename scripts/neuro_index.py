# Abstract block, in the layouts these papers actually use: a labelled heading,
# or the opening block before the Introduction heading.
ABS_RE = re.compile(
    r"(?:^|\n)\s*(?:Abstract|ABSTRACT)\s*[-:.\u2014]?\s*\n(.+?)"
    r"(?=\n\s*(?:1[\.\s]|I[\.\s]?\s*N|Introduction|INTRODUCTION|Keywords|Index Terms)\b)",
    re.S,
)


def abstract_of(text: str) -> str:
    """Abstract prose, or the first substantive paragraph if unlabelled."""
    m = ABS_RE.search(text[:9000])
    if m:
        body = " ".join(m.group(1).split())
        if len(body) > 120:
            return body
    for para in re.split(r"\n\s*\n", text[:6000]):
        para = " ".join(para.split())
        para = re.sub(r"^(Abstract|ABSTRACT)\s*[-:.\u2014]?\s*", "", para)
        if len(para) > 180:
            return para
    return ""


def sentences(text: str) -> list[str]:
    text = re.sub(r"\s*\n\s*", " ", text)
    parts = re.split(r"(?<=[.!?])\s+(?=[A-Z(“\"'(\[])", text)
    out = []
    for p in parts:
        p = " ".join(p.split())
        # drop citation debris left by reference extraction
        p = re.sub(r"\s*,\s*,+", ", ", p)
        p = re.sub(r"\s*[\[\(]\s*[\]\)]\s*", " ", p)
        if len(p) > 40:
            out.append(p)
    return out


def count_before(sent: str) -> int | None:
    """How many of something: 'three fully-connected layers', '2 conv layers'."""
    m = re.search(
        r"\b(\d+|one|two|three|four|five|six|seven|eight|nine|ten)\s+"
        r"([a-z\- ]{0,18}?)(?:conv|dense|pool|lstm|gru|recurrent|hidden|linear|attention)",
        sent,
        re.I,
    )
    if not m:
        return None
    raw = m.group(1).lower()
    return int(raw) if raw.isdigit() else NUM_WORDS.get(raw)


UNIT_PATTERNS = [
    r"(\d+)\s*(?:hidden\s+)?(?:units|neurons|nodes)\s*(?:in|per|each)?",
    r"(?:hidden\s+)?(?:layer|units|layers?)\s*(?:of|with|having|containing)\s*(\d+)\s*(?:units|neurons|nodes)",
    r"(\d+)\s*(?:input|output)\s+(?:units|neurons|nodes)",
    r"(\d+)\s*x\s*\d+\s*(?:convolutional|conv|filter)",
    r"(\d+)\s*(?:channels|filters|feature maps)",
]


def extract_units(sent: str, label: str | None = None) -> int | None:
    """Width of a layer, as the paper states it.

    Tried label-first, because 'output layer of 2 units' and '2 input units'
    both match the generic patterns but mean different things.
    """
    if label:
        pat = rf"{label}[^.]{{0,40}}?(\d+)\s*(?:units|neurons|nodes|channels|filters|features)"
        m = re.search(pat, sent, re.I)
        if m:
            return int(m.group(1))
    for pat in UNIT_PATTERNS:
        m = re.search(pat, sent, re.I)
        if m:
            try:
                return int(m.group(1))
            except (TypeError, ValueError):
                continue
    return None


def detect_layers(sents: list[str]) -> tuple[list[dict], list[str]]:
    """Build an ordered layer list from the paper's own architecture sentences.

    Returns (layers, quotes). Layer dicts carry the matched sentence so the UI
    can show why the layer is there.
    """
    quotes: list[str] = []
    # A sentence qualifies either by naming a layer kind outright, or by one of
    # the architecture cues. The kind match has to stand on its own: many papers
    # state their architecture with none of the cue phrases at all, and gating on
    # the cues alone silently discarded those.
    strong = [s for s in sents if any(re.search(p, s, re.I) for _, ps in LAYER_RULES for p in ps)]
    cand = [s for s in sents if any(c in s.lower() for c in ARCH_CUES)]
    ordered = strong + [s for s in cand if s not in strong]

    layers: list[dict] = []
    seen: set[str] = set()

    def add(kind: str, sent: str, label: str) -> None:
        key = f"{kind}:{label}"
        if key in seen:
            return
        seen.add(key)
        units = extract_units(sent, label)
        layers.append({"kind": kind, "label": label, "units": units, "quote": sent})

    # pass 1: input / output markers first so the chain starts and ends right
    for sent in ordered[:30]:
        low = sent.lower()
        if "input" in low and "output" not in low and not any(l["kind"] == "input" for l in layers):
            add("input", sent, "input")
        if re.search(r"output\s*(?:layer|unit|neuron)|readout", low) and not any(
            l["kind"] == "output" for l in layers
        ):
            add("output", sent, "output")

    # pass 1b: "a three-layer MLP" / "two hidden layers" states the depth
    # explicitly, so the chain is filled in rather than collapsing to one box.
    for sent in ordered[:30]:
        if not layers:
            continue
        m = re.search(
            r"\b(\d+|one|two|three|four|five|six|seven|eight|nine|ten)\s*"
            r"(?:[- ]layer|hidden layers?|-hidden-layer)",
            sent,
            re.I,
        )
        if not m:
            continue
        raw = m.group(1).lower()
        depth = int(raw) if raw.isdigit() else NUM_WORDS.get(raw)
        if not depth or depth < 2 or depth > 12:
            continue
        inner = [k for k in ("conv", "recurrent", "dense", "pool", "attention") if any(l["kind"] == k for l in layers)]
        kind = inner[0] if inner else "dense"
        label = LAYER_LABEL_SHORT.get(kind, kind)
        have = sum(1 for l in layers if l["kind"] == kind)
        for i in range(depth - have):
            layers.append(
                {"kind": kind, "label": label if i == 0 else f"{label} {i + 1}", "units": None, "quote": sent}
            )

    # pass 2: middle layers, in the order they are mentioned
    for sent in ordered[:30]:
        for kind, pats in LAYER_RULES:
            if kind in ("input", "output"):
                continue
            for p in pats:
                m = re.search(p, sent, re.I)
                if m:
                    label = LAYER_LABEL_SHORT.get(kind, kind)
                    add(kind, sent, label)
                    break

    # order: input, then middle, then output
    rank = {"input": 0, "conv": 1, "pool": 2, "dense": 3, "recurrent": 4,
            "attention": 5, "skip": 6, "output": 7, "unknown": 8}
    layers.sort(key=lambda l: rank.get(l["kind"], 9))

    for s in ordered[:3]:
        quotes.append(s)
    return layers[:14], quotes[:3]


LAYER_LABEL_SHORT = {
    "conv": "conv", "pool": "pool", "recurrent": "recurrent",
    "attention": "attention", "skip": "skip", "dense": "dense",
    "input": "input", "output": "output", "step": "step", "unknown": "unstated",
}


def detect_rules(sents: list[str], rules, limit: int = 6):
    """First-match-wins over a rule table of (key, label, cues)."""
    out = []
    for key, label, cues in rules:
        for s in sents:
            if any(re.search(c, s, re.I) for c in cues):
                quote = s
                if isinstance(label, tuple):
                    label, quote = label, s
                out.append({"key": key, "label": label, "quote": quote})
                break
        if len(out) >= limit:
            break
    return out


def first_match(hay: str, rules: list[tuple[str, tuple[str, ...]]]) -> str:
    for name, keys in rules:
        if any(k in hay for k in keys):
            return name
    return "other"


def classify_relevance(title: str, hay: str) -> str:
    t = title.lower()
    neuro = any(c in hay for c in NEURO_CUES) or any(c in t for c in NEURO_CUES)
    off = [c for c in OFF_TOPIC_CUES if c in t]

    if off and not any(c in t for c in ("neural", "network", "controller", "policy")):
        return "off-topic"
    if neuro and not off:
        return "neuroevolution"
    if neuro and off:
        return "adjacent"
    return "adjacent"


