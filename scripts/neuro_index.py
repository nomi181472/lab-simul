def pdf_text(path: pathlib.Path) -> str:
    """Extracted body text, cached per PDF.

    Raw `pdftotext` (no -layout): -layout interleaves the two-column body of
    IEEE/ACM papers line by line, which shreds every sentence this lab quotes.
    """
    if not path.exists():
        return ""
    CACHE.mkdir(parents=True, exist_ok=True)
    out = CACHE / (path.stem + ".txt")
    if out.exists() and out.stat().st_size > 200:
        return out.read_text(errors="replace")
    try:
        r = subprocess.run(
            ["pdftotext", "-q", str(path), "-"],
            capture_output=True,
            timeout=120,
        )
        text = r.stdout.decode("utf-8", "replace")
    except Exception:
        text = ""
    out.write_text(text)
    return text


def pdf_pages(path: pathlib.Path) -> int:
    if not path.exists():
        return 0
    try:
        r = subprocess.run(
            ["pdfinfo", str(path)], capture_output=True, timeout=60, text=True
        )
        m = re.search(r"^Pages:\s+(\d+)", r.stdout, re.M)
        return int(m.group(1)) if m else 0
    except Exception:
        return 0


def head_text(text: str) -> str:
    return text[:HEAD_CHARS]


