def enrich_row(row: dict) -> dict:
    pdf = CORPUS / row["fileName"]
    text = pdf_text(pdf) if pdf.exists() else ""
    hay = (row["title"] + "\n" + head_text(text)).lower()

    row["pdfBytes"] = pdf.stat().st_size if pdf.exists() else 0
    row["pages"] = pdf_pages(pdf) if pdf.exists() else 0
    row["task"] = first_match(hay, PHENOTYPE_RULES)
    row["family"] = first_match(hay, FAMILY_RULES)
    row["encoding"] = first_match(hay, ENCODING_RULES)
    _, tags = (list(TAG_RULES), None)
    fired = [n for n, keys in TAG_RULES if any(k in hay for k in keys)]
    row["tags"] = fired
    row["relevance"] = classify_relevance(row["title"], hay)
    return row


def q(s: str) -> str:
    s = str(s)
    for _ in range(3):
        t = unescape(s)
        if t == s:
            break
        s = t
    return json.dumps(s, ensure_ascii=False)


