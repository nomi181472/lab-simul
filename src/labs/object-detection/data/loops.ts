/** Research map: nodes are episodes, directed by leadsTo. */
export type MapNode = {
  id: string;
  year: number;
  title: string;
};

export function buildResearchGraph() {
  const nodes: MapNode[] = RESEARCH_EPISODES.map((e) => ({
    id: e.id,
    year: e.year,
    title: e.title,
  }));
  const edges: { from: string; to: string }[] = [];
  for (const e of RESEARCH_EPISODES) {
    for (const to of e.leadsTo) edges.push({ from: e.id, to });
  }
  return { nodes, edges };
}

